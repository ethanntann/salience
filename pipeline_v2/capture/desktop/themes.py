def block(selector: str, values: dict, scheme: str) -> str:
    body = "".join(f"  --{key.replace('_', '-')}: {value};\n" for key, value in values.items())
    return f"{selector} {{\n  color-scheme: {scheme};\n{body}}}\n"


def render() -> str:
    out = [BEGIN, ":root {\n  --display: \"Zen Kaku Gothic New\", \"Segoe UI\", sans-serif;\n"
                  "  --text: \"M PLUS 1 Code\", Consolas, monospace;\n"
                  "  --pattern-ink: color-mix(in srgb, var(--ink) 5%, transparent);\n"
                  "  --pattern-ink-strong: color-mix(in srgb, var(--ink) 16%, transparent);\n}\n"]
    for name, (_, light, dark) in PALETTES.items():
        is_default = name == DEFAULT
        tag = "" if is_default else f'[data-palette="{name}"]'
        out.append(block((":root, " if is_default else "") + f':root[data-palette="{name}"]', light, "light"))
        out.append("@media (prefers-color-scheme: dark) {\n"
                   + block(f':root{tag}:not([data-theme="light"])', dark, "dark").replace("\n", "\n  ").rstrip() + "\n}\n")
        out.append(block(f':root[data-theme="dark"]{tag}', dark, "dark"))
    for name, (_, image, size) in PATTERNS.items():
        selector = (":root, " if name == DEFAULT_PATTERN else "") + f':root[data-pattern="{name}"]'
        out.append(f"{selector} {{ --pattern: {image}; --pattern-size: {size}; }}\n")
    out.append(END)
    return "\n".join(out)


def catalogue() -> dict:
    """What Settings shows: each palette's colours for its preview, each pattern's drawing."""
    keep = ("ground", "surface", "ink", "select", "strong")
    return {
        "palettes": [{"name": n, "label": label, "light": {k: light[k] for k in keep}, "dark": {k: dark[k] for k in keep}}
                     for n, (label, light, dark) in PALETTES.items()],
        "patterns": [{"name": n, "label": label, "image": image, "size": size} for n, (label, image, size) in PATTERNS.items()],
        "default_palette": DEFAULT, "default_pattern": DEFAULT_PATTERN,
    }


def install() -> None:
    import json

    (CSS.parent / "themes.json").write_text(json.dumps(catalogue(), indent=1), encoding="utf-8")
    text = CSS.read_text(encoding="utf-8")
    start = text.index(BEGIN) if BEGIN in text else text.index(":root {")
    end = text.index(END) + len(END) if END in text else text.index("* { box-sizing: border-box; }")
    CSS.write_text(text[:start] + render() + "\n\n" + text[end:].lstrip("\n"), encoding="utf-8")


def luminance(hex_: str) -> float:
    def channel(c: int) -> float:
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def check() -> list[str]:
    """Each text colour on the grounds it is read on, below 4.5:1."""
    problems = []
    for name, (_, *modes) in PALETTES.items():
        for mode, p in zip(("light", "dark"), modes):
            pairs = [(k, g) for k in ("ink", "ink_soft", "muted", "faint") for g in ("ground", "surface")]
            pairs += [("select_ink", "select"), ("strong_ink", "strong")]
            for text_key, ground_key in pairs:
                ratio = contrast(p[text_key], p[ground_key])
                if ratio < 4.5:
                    problems.append(f"{name} {mode}: {text_key} on {ground_key} {ratio:.2f}")
    return problems


